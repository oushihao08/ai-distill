- 网址：含地区或机构标识的整体替换为“**”。
- 案号、证件号、账号、单号、核准号、柜员号、网点号等识别编号：去掉空格和连字符后计算位数，首2位和末2位保留，中间逐位替换为“*”；不足5位全部替换为“*”，分隔符原位保留。页码、序号、法条序号、车型年款及案号中的案件类型字样不属于识别编号。
